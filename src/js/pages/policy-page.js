const key = document.body.dataset.policy;
const policy = policies[key];
const main = document.querySelector("[data-policy-content]");
const header = document.querySelector("#site-header");
const footer = document.querySelector("#site-footer");

if (!policy || !main || !header || !footer) {
  throw new Error("تعذر تحميل صفحة السياسة المطلوبة.");
}

renderHeader(header, { basePath: "../../", currentPage: "policy" });
renderFooter(footer, { basePath: "../../" });
document.title = `${policy.title} | إتقان للتعلم`;

const title = document.createElement("h1");
title.textContent = policy.title;
main.querySelector("[data-policy-title]").replaceChildren(title);
main.querySelector("[data-policy-intro]").textContent = policy.intro;

const sections = document.createDocumentFragment();
for (const [headingText, items] of policy.sections) {
  const section = document.createElement("section");
  section.className = "site-content__section";
  const heading = document.createElement("h2");
  heading.textContent = headingText;
  const list = document.createElement("ul");
  for (const item of items) {
    const listItem = document.createElement("li");
    listItem.textContent = item;
    list.append(listItem);
  }
  section.append(heading, list);
  sections.append(section);
}
main.querySelector("[data-policy-sections]").replaceChildren(sections);
main.setAttribute("aria-busy", "false");
